import re
p = "src/render/icons.h"
s = open(p).read()
names = list(ART)
add = ""
for n in names:
    rows = [r for r in ART[n].strip("\n").split("\n")]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), n
    bits = ["0b" + r.replace("#", "1").replace(".", "0") for r in rows]
    add += "    {// %s\n     %s,\n     %s},\n" % (n, ", ".join(bits[:6]), ", ".join(bits[6:]))
s = s.replace("Layout, Help, Count };", "Layout, Help, " + ", ".join("M" + n for n in names) + ", Count };")
i = s.rindex("};")
s = s[:i] + add + s[i:]
open(p, "w").write(s)
m = "src/core/module.h"
t = open(m).read()
t = t.replace("Mux, Dmx, Tilt };", "Mux, Dmx, Tilt, " + ", ".join(names) + " };")
open(m, "w").write(t)
print(names)
