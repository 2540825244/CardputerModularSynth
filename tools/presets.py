GAIN = {}  # preset name -> OUT gain dB (tools/preset_levels.py sets it from the bench)
EXTRA = os.path.join(os.path.dirname(__file__), "presets_more.py")
if os.path.exists(EXTRA):
    exec(open(EXTRA).read())


def apply_out(name, mods, inamt):
    """Every OUT: DEST LINE; GAIN dB > 0 is its TRIM, < 0 its input amount."""
    g = GAIN.get(name, 0)
    for k, (t, cell, params) in mods.items():
        if t == "out":
            params["dest"] = 1
            if g > 0: params["trim"] = round(g, 1)
            if g < 0: inamt.setdefault(k, {})["in"] = round(10 ** (g / 20), 3)


def to_json(mods, cables, inamt):
    ids = {k: i + 1 for i, k in enumerate(mods)}
    out_amt = {}
    for c in cables:
        if len(c) > 4 and c[4] != 1:
            out_amt.setdefault(c[0], {})[c[1]] = c[4]
    ms = []
    for k, (t, cell, params) in mods.items():
        m = {"id": ids[k], "type": t, "page": cell // 48, "cell": cell % 48, "params": params}
        if k in out_amt: m["amounts"] = out_amt[k]
        if k in inamt: m["inamounts"] = inamt[k]
        ms.append(m)
    cs = [{"from": [ids[c[0]], c[1]], "to": [ids[c[2]], c[3]]} for c in cables]
    return json.dumps({"format": 1, "modules": ms, "cables": cs}, separators=(",", ":"))


def main():
    lines = ['// Generated by tools/presets.py: edit the table there, not this file.',
             '#include "presets.h"', '', 'namespace {', 'const Preset kPresets[] = {']
    for name, mods, cables, inamt in P:
        assert len(name) <= 6, name
        apply_out(name, mods, inamt)
        js = to_json(mods, cables, inamt).replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    {"%s",\n     "%s"},' % (name, js))
    lines += ['};', '}  // namespace', '',
              'const Preset* presets(int* count) {',
              '    if (count) *count = (int)(sizeof(kPresets) / sizeof(kPresets[0]));',
              '    return kPresets;', '}', '']
    path = os.path.join(os.path.dirname(__file__), "..", "src", "core", "presets.cpp")
    open(path, "w").write("\n".join(lines))
    print("wrote", len(P), "presets")


main()
